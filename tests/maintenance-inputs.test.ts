import assert from "node:assert/strict";
import { readFile, readdir, rename, rm, utimes } from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { SourceManager } from "../src/sources/manager.js";
import { PLAN_LIFETIME_MS } from "../src/application/retention.js";
import { stableId } from "../src/domain/identity.js";
import { applicationFixture } from "./helpers/application.js";
import { upgradeFixture } from "./helpers/adapter-upgrade.js";
const limits = { ttlMs: 0, keepNewest: 0, maxBytes: 0 };
test("maintenance preserves offline catalog/install/repair inputs and reclaims only unreferenced snapshots", async t => {
  const f = await applicationFixture(t); await f.add("a"); await f.register();
  const cache = path.join(path.dirname(f.home), `.harnessbrew-cache-${stableId(f.home)}`);
  const unused = await new SourceManager(path.join(cache, "sources")).prepare({ name: "unused/assets", url: f.repository });
  await rename(f.repository, `${f.repository}-offline`);
  const preview = await f.service.planMaintenance(limits);
  assert.equal(preview.objects.find(o => o.path === path.dirname(unused.contentLocation))?.status, "deletable");
  assert.ok(preview.objects.some(o => o.kind === "source" && o.reasons.includes("current-state")));
  const result = await f.service.applyMaintenance(preview.planId); assert.ok(result.deleted.includes(path.dirname(unused.contentLocation)));
  assert.equal((await f.service.query({ kind: "search" })).length, 1);
  assert.ok((await f.service.query({ kind: "info", coordinate: "a" })).available);
  await f.service.execute({ kind: "asset.install", coordinate: "a", placements: [f.placement] });
  const installed = await f.service.query({ kind: "list" }), digest = installed.assets[0]!.contentDigest;
  await rm(path.join(f.home, "content", digest.slice(7)), { recursive: true });
  await f.service.execute({ kind: "repair", coordinate: "a", restoreContent: true });
  assert.ok(await readFile(path.join(f.home, "content", digest.slice(7), "SKILL.md"), "utf8"));
});
test("current and valid upgrade plugins survive maintenance; expired unselected candidate is collected", async t => {
  const f = await upgradeFixture(t), cache = path.join(path.dirname(f.home), `.harnessbrew-cache-${stableId(f.home)}`);
  const validRequest = await f.request(), valid = await f.service.plan(validRequest);
  const third = await f.plugin("3", "third"), thirdInspection = await f.service.inspectAdapterUpgrade({ name: "test-adapter", module: third });
  const expired = await f.service.plan({ ...validRequest, module: third, authorizedSignature: thirdInspection.candidate.signature });
  const expiredFile = path.join(cache, "plans", `${expired.planId}.json`), old = new Date(Date.now() - PLAN_LIFETIME_MS - 1000);
  await utimes(expiredFile, old, old);
  const preview = await f.service.planMaintenance(limits);
  const validCache = path.join(cache, "plugins", validRequest.authorizedSignature.slice(7)), expiredCache = path.join(cache, "plugins", thirdInspection.candidate.signature.slice(7));
  assert.equal(preview.objects.find(o => o.path === validCache)?.status, "protected");
  assert.equal(preview.objects.find(o => o.path === expiredCache)?.status, "deletable");
  assert.ok(preview.objects.some(o => o.kind === "plugin" && o.reasons.includes("current-state")));
  await f.service.applyMaintenance(preview.planId);
  await assert.rejects(readdir(expiredCache), { code: "ENOENT" });
  await rename(f.repository, `${f.repository}-offline`);
  await f.service.apply(valid.planId);
  assert.equal((await f.service.query({ kind: "adapters" })).find(a => a.name === "test-adapter")?.signature, validRequest.authorizedSignature);
  assert.ok((await f.service.doctor()).healthy);
});
