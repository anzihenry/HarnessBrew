import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, readdir, symlink, utimes, writeFile } from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { ownedCacheDirectory } from "../src/application/cache.js";
import { CacheLeases } from "../src/application/cache-leases.js";
import { PLAN_LIFETIME_MS } from "../src/application/retention.js";
import { hash, stableId } from "../src/domain/identity.js";
import { canonicalJson } from "../src/domain/validation.js";
import { runCli } from "../src/cli.js";
import { applicationFixture } from "./helpers/application.js";
const limits = { ttlMs: 0, keepNewest: 0, maxBytes: 0 };
test("maintenance preview preserves files, saved plans, unknown entries and user quarantine", async t => {
  const f = await applicationFixture(t); await f.add("a"); await f.register();
  const plan = await f.service.plan({ kind: "asset.install", coordinate: "a" });
  const cache = path.join(path.dirname(f.home), `.harnessbrew-cache-${stableId(f.home)}`);
  const orphan = await ownedCacheDirectory(path.join(cache, "prepared"), randomUUID(), "prepared"); await writeFile(path.join(orphan, "payload"), "unreferenced");
  const unknown = path.join(cache, "prepared", "user-quarantine"); await mkdir(unknown); await writeFile(path.join(unknown, "note"), "user evidence");
  const linked = path.join(cache, "restores"); await symlink(f.repository, linked);
  const unsafe = await f.service.planMaintenance(limits);
  assert.ok(unsafe.objects.every(o => o.status !== "deletable"));
  assert.ok(unsafe.diagnostics.includes("unsafe-restores-directory"));
  const { unlink } = await import("node:fs/promises"); await unlink(linked);
  const preview = await f.service.planMaintenance(limits);
  assert.equal(preview.objects.find(o => o.path === orphan)?.status, "deletable");
  assert.equal(preview.objects.find(o => o.path === unknown)?.status, "unknown");
  assert.equal(preview.objects.find(o => o.path.endsWith(`${plan.planId}.json`))?.status, "protected");
  assert.ok(preview.objects.some(o => o.kind === "prepared" && o.reasons.includes("saved-plan-reference")));
  assert.ok(preview.overBudgetBytes > 0);
  assert.equal(await readFile(path.join(orphan, "payload"), "utf8"), "unreferenced");
  assert.equal(await readFile(path.join(unknown, "note"), "utf8"), "user evidence");
  const saved = JSON.parse(await readFile(path.join(cache, "maintenance", `${preview.planId}.json`), "utf8"));
  assert.equal(saved.digest, hash(canonicalJson(saved.preview))); assert.deepEqual(saved.preview, preview);
});
test("active preparation and corrupt references fail closed; expired pins remain until retirement", async t => {
  const f = await applicationFixture(t); await f.register();
  const plan = await f.service.plan({ kind: "tap.trust", name: "test/assets" });
  const cache = path.join(path.dirname(f.home), `.harnessbrew-cache-${stableId(f.home)}`), leases = new CacheLeases(cache);
  const old = new Date(Date.now() - PLAN_LIFETIME_MS - 1000);
  await utimes(path.join(cache, "plans", `${plan.planId}.json`), old, old);
  await leases.withLease(async () => {
    const preview = await f.service.planMaintenance(limits);
    assert.ok(preview.objects.filter(o => o.owned).every(o => o.status === "protected"));
    assert.ok(preview.objects.some(o => o.reasons.includes("active-cache-lease")));
  });
  const preview = await f.service.planMaintenance(limits);
  assert.equal(preview.objects.find(o => o.path.endsWith(`${plan.planId}.json`))?.status, "protected");
  await writeFile(path.join(cache, "references", "unknown.tmp"), "interrupted");
  const blocked = await f.service.planMaintenance(limits);
  assert.ok(blocked.objects.every(o => o.status !== "deletable"));
  assert.ok(blocked.diagnostics.includes("unreadable-cache-protection"));
});
test("CLI maintenance preview emits one JSON document and validates limits", async t => {
  const f = await applicationFixture(t); const output: string[] = [], errors: string[] = [];
  const io = { stdout: (s: string) => output.push(s), stderr: (s: string) => errors.push(s) };
  assert.equal(await runCli(["maintenance", "--dry-run", "--json", "--keep-newest", "0"], io, f.options), 0);
  assert.equal(output.length, 1); assert.equal(errors.length, 0); assert.equal(JSON.parse(output[0]!).mode, "preview");
  assert.equal(JSON.parse(output[0]!).result.policy.keepNewest, 0);
  output.length = 0;
  assert.equal(await runCli(["maintenance", "--dry-run", "--json", "--ttl-days", "-1"], io, f.options), 2);
  assert.equal(JSON.parse(output[0]!).error.code, "INVALID_ARGUMENT");
  assert.ok(!(await readdir(f.root)).includes("home"));
});
