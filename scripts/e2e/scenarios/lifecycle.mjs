import assert from "node:assert/strict";
import { lstat, readFile } from "node:fs/promises";
import path from "node:path";
import { createTapFixture } from "../fixture-tap.mjs";
import { assertPathMissing } from "../assertions.mjs";
export async function lifecycleScenario({ environment, cli }) {
  const fixture = await createTapFixture(environment, { id: "lifecycle" });
  assert.equal((await cli.run(["--version"])).stdout.trim(), environment.artifact.package.version);
  assert.match((await cli.run(["help"])).stdout, /Git-native package manager/u);
  await cli.runJson(["tap", "add", fixture.name, fixture.remote]);
  assert.equal((await cli.runJson(["tap", "list"])).envelope.result[0].trusted, false);
  assert.deepEqual((await cli.runJson(["search", "main-skill"])).envelope.result.map(a => a.coordinate), ["e2e/assets/main-skill"]);
  assert.equal((await cli.runJson(["info", "main-skill"])).envelope.result.available.manifest.kind, "skill");
  const untrusted = await cli.runJson(["install", "main-skill"], { expectExitCode: 1 });
  assert.equal(untrusted.envelope.error.code, "SOURCE_UNTRUSTED");
  await cli.runJson(["tap", "trust", fixture.name]);
  const args = ["--root", environment.paths.codexRoot];
  await cli.runJson(["install", "main-skill", ...args]);
  const installed = (await cli.runJson(["list"])).envelope.result;
  assert.deepEqual(installed.assets.map(a => a.coordinate), ["e2e/assets/helper-skill", "e2e/assets/main-skill"]);
  assert.equal(installed.assets[0].commit.value, fixture.v1Commit);
  const target = path.join(environment.paths.codexRoot, "skills", "main-skill");
  assert.ok((await lstat(target)).isSymbolicLink()); assert.match(await readFile(path.join(target, "SKILL.md"), "utf8"), /v1/u);
  assert.equal((await cli.runJson(["doctor"])).envelope.result.healthy, true);
  await cli.runJson(["unlink", "main-skill", ...args]); await assertPathMissing(target);
  await cli.runJson(["link", "main-skill", ...args]);
  await cli.runJson(["remove", "main-skill"]); await assertPathMissing(target);
  await cli.runJson(["cleanup"]); await cli.runJson(["tap", "remove", fixture.name]);
  assert.deepEqual((await cli.runJson(["list"])).envelope.result.assets, []);
  assert.deepEqual((await cli.runJson(["tap", "list"])).envelope.result, []);
}
